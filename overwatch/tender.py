"""Deterministic comparison of manually verified simulation bids.

Discovery is not qualification. Verification booleans are inputs from a trusted
review step, never inferred from company enrichment or generated by a model.
"""
from .errors import Rejected
from .policy import finite, money


def compare_bids(bids, *, now, currency):
    ranked, excluded = [], []
    suppliers = set()
    expected_quantity = None
    expected_scope = None
    for bid in bids:
        supplier = bid.get("supplier")
        if not isinstance(supplier, str) or not supplier or supplier in suppliers:
            raise Rejected("supplier must be present and unique")
        suppliers.add(supplier)
        quantity = bid.get("quantity")
        if isinstance(quantity, bool) or not isinstance(quantity, int) or quantity <= 0:
            raise Rejected("quantity must be a positive integer")
        if expected_quantity is None:
            expected_quantity = quantity
            expected_scope = bid.get("scope_id")
        if quantity != expected_quantity or bid.get("scope_id") != expected_scope:
            raise Rejected("bid scope and quantity must match before comparison")
        total = money(bid.get("unit_price")) * quantity + money(bid.get("freight")) + money(bid.get("tax"))
        reasons = []
        if bid.get("qualified") is not True:
            reasons.append("qualification unverified")
        if bid.get("screened") is not True:
            reasons.append("compliance screening incomplete")
        if bid.get("availability_confirmed") is not True:
            reasons.append("written availability commitment missing")
        if not bid.get("evidence_id"):
            reasons.append("written bid receipt missing")
        if finite(bid.get("expires_at", 0)) <= now:
            reasons.append("bid expired")
        if bid.get("currency") != currency:
            reasons.append("currency mismatch; no implicit FX conversion")
        if reasons:
            excluded.append(dict(supplier=supplier, reason="; ".join(reasons)))
        else:
            ranked.append({**bid, "total": str(total)})
    ranked.sort(key=lambda b: (money(b["total"]), b["supplier"]))
    return dict(ranked=ranked, excluded=excluded, currency=currency,
                recommendation=ranked[0]["supplier"] if ranked else None,
                status="DRAFT_ONLY", methodology="Lowest total among eligible bids; identical scope required")
